"""Generate an inert inline SVG module from retained SVG Repo originals."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET
ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / 'assets/pwa-ui'
ALLOWED_TAGS = {'path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse', 'g'}
ALLOWED_ATTRS = {'d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'width', 'height', 'points', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'stroke-miterlimit', 'fill-rule', 'clip-rule', 'opacity'}
icons = {}
for item in json.loads((DIR / 'sources.json').read_text())['icons']:
    svg = ET.fromstring((DIR / (item['name'] + '.svg')).read_text())
    assert svg.attrib['viewBox'] == '0 0 24 24'
    def render(node):
        tag = node.tag.split('}')[-1]
        assert tag in ALLOWED_TAGS, tag
        assert set(node.attrib) <= ALLOWED_ATTRS, node.attrib
        attrs = dict(node.attrib)
        for name in ('fill', 'stroke'):
            if name in attrs and attrs[name] in ('#000000', '#000', 'black'):
                attrs[name] = 'currentColor'
        return '<' + tag + ''.join(' ' + k + '=' + json.dumps(v) for k, v in attrs.items()) + '>' + ''.join(render(c) for c in node) + '</' + tag + '>'
    icons[item['name']] = ''.join(render(c) for c in svg)
module = "// Generated by debug/generate-pwa-ui-icons.py; do not hand-edit shapes.\n// Dazzle UI via SVG Repo, CC BY 4.0; adapted to currentColor. See assets/pwa-ui/README.md.\n(function(root) {\n'use strict';\nconst shapes = " + json.dumps(icons, indent=2) + ";\nconst icon = name => {\n  if (!Object.hasOwn(shapes, name)) throw new Error('Unknown PWA icon');\n  return `<svg class=\"pwa-icon\" data-pwa-icon=\"${name}\" aria-hidden=\"true\" focusable=\"false\" viewBox=\"0 0 24 24\" fill=\"none\" xmlns=\"http://www.w3.org/2000/svg\">${shapes[name]}</svg>`;\n};\nif (typeof module !== 'undefined') module.exports = icon;\nif (root.document) root.FluidPwaIcon = icon;\n}(typeof window !== 'undefined' ? window : globalThis));\n"
(ROOT / 'app/pwa-ui-icons.js').write_text(module, encoding='utf-8')
print('Generated', len(icons), 'inert SVG icons')
